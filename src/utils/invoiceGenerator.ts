import { LeadRfqItem } from '../types/cms';
import { PortalQuoteAndInvoice } from '../types/portal';

/**
 * Automatically creates an enterprise-compliant Pro-Forma Tax Invoice or Formal Quotation
 * from an RFQ Lead or customer submission.
 */
export function buildAutomatedInvoiceFromLead(
  lead: LeadRfqItem,
  exchangeRate = 1580,
  defaultState = 'Lagos State'
): PortalQuoteAndInvoice {
  const subtotalUSD =
    lead.totalUSD > 0
      ? lead.totalUSD
      : lead.lineItems.reduce((acc, it) => acc + (it.unitPriceUSD || 0) * it.quantity, 0);

  const vatPercent = 7.5; // Standard statutory VAT in Nigeria
  const discountPercent = 0;
  const deliveryState = lead.deliveryState || defaultState;

  // Compute standard regional freight estimate based on state
  let freightChargeUSD = 85;
  if (deliveryState.includes('Rivers') || deliveryState.includes('Delta') || deliveryState.includes('Harcourt')) {
    freightChargeUSD = 320;
  } else if (deliveryState.includes('Abuja') || deliveryState.includes('FCT')) {
    freightChargeUSD = 310;
  } else if (deliveryState.includes('Kano') || deliveryState.includes('Kaduna')) {
    freightChargeUSD = 350;
  } else if (deliveryState.includes('Ogun') || deliveryState.includes('Oyo')) {
    freightChargeUSD = 160;
  }

  const taxableUSD = subtotalUSD + freightChargeUSD;
  const vatUSD = Number((taxableUSD * (vatPercent / 100)).toFixed(2));
  const grandTotalUSD = Number((taxableUSD + vatUSD).toFixed(2));

  const quoteRef = lead.refCode.replace('RFQ', 'QUO');
  const proformaInvoiceRef = lead.refCode.replace('RFQ', 'INV');

  const today = new Date().toISOString().split('T')[0];
  const validUntil = new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString().split('T')[0];

  return {
    id: `inv-${lead.id}`,
    quoteRef,
    proformaInvoiceRef,
    linkedRfqRef: lead.refCode,
    customerCompany: lead.clientCompany || 'Corporate Procurement Client',
    contactName: lead.clientName || 'Procurement Executive',
    contactEmail: lead.clientEmail || 'procurement@client.com',
    deliveryState,
    currencyMode: 'NGN',
    freightChargeUSD,
    paymentValidityTerms:
      '30 Days Quote Validity • Corporate PO (Net-30 Days) for Approved Institutional Clients • Standard ISO 17025 Traceable',
    lineItems: lead.lineItems.map((item, idx) => ({
      id: item.id || `line-${idx + 1}`,
      description: item.name,
      model: item.model || 'Standard Metrology Model',
      qty: item.quantity || 1,
      unitPriceUSD: item.unitPriceUSD || 0,
    })),
    subtotalUSD,
    discountPercent,
    vatPercent,
    totalUSD: grandTotalUSD,
    exchangeRateNGN: exchangeRate,
    quoteStatus: lead.status === 'Closed' ? 'Customer Approved' : 'Sent for Approval',
    paymentStatus: lead.status === 'Closed' ? 'Verified & Paid' : 'Unpaid',
    paymentMethod: 'Bank Wire Transfer (NGN)',
    issuedDate: today,
    validUntil,
    notes: `Official Commercial Pro-Forma Tax Invoice generated by Samstrust Technologies Limited (RC 9898142 / TIN 10293847-0001). All instruments calibrated per ISO/IEC 17025:2017 standards before site deployment.`,
  };
}
